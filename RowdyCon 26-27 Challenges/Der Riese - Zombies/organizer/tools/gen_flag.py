#!/usr/bin/env python3
"""Generate flag_data.js for the Der Riese challenge.

Usage: python3 tools/gen_flag.py 'flag{...}'

Replicates the in-game vault scheme (js/05_vault.js):
  chain = sha256("DER_RIESE::MAINFRAME::115")
  for r in 2..100: chain = sha256(chain + ":" + str(r))
  key = sha256(chain + ":FLAG")
  keystream block i = sha256(key + ":" + str(i))  (32 bytes each)
  ct = pt XOR keystream ; tag = sha256(pt)
"""
import hashlib
import json
import os
import sys

SEED = "DER_RIESE::MAINFRAME::115"
TARGET_ROUND = 100


def h(s: str) -> str:
    return hashlib.sha256(s.encode()).hexdigest()


def chain_state(target_round: int = TARGET_ROUND) -> str:
    st = h(SEED)
    for r in range(2, target_round + 1):
        st = h(st + ":" + str(r))
    return st


def keystream(key: str, n: int) -> bytes:
    out = b""
    i = 0
    while len(out) < n:
        out += hashlib.sha256((key + ":" + str(i)).encode()).digest()
        i += 1
    return out[:n]


def encrypt(flag: str) -> dict:
    pt = flag.encode()
    key = h(chain_state() + ":FLAG")
    ks = keystream(key, len(pt))
    ct = bytes(a ^ b for a, b in zip(pt, ks))
    return {"ct": ct.hex(), "tag": hashlib.sha256(pt).hexdigest()}


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    flag = sys.argv[1]
    data = encrypt(flag)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "flag_data.js")
    with open(path, "w") as f:
        f.write("// Generated by tools/gen_flag.py — encrypted flag for the mainframe vault.\n")
        f.write("ZM.FLAG = " + json.dumps(data) + ";\n")
    print("wrote", path)
    print("ct  =", data["ct"])
    print("tag =", data["tag"])


if __name__ == "__main__":
    main()
